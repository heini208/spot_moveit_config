#!/usr/bin/env python3
"""Generate conservative collision meshes offline; requires NumPy and SciPy."""

import argparse
from collections import Counter
import hashlib
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull


SOURCES = {
    f"{side}_hip.obj": (f"meshes/base/visual/{side}_hip.obj",)
    for side in ("front_left", "front_right", "rear_left", "rear_right")
}
SOURCES["arm_link_hr0.obj"] = (
    "meshes/arm/visual/arm_link_sh1.obj",
    "meshes/arm/visual/arm_link_hr0.obj",
    "meshes/arm/collision/arm_link_hr0.obj",
)
TOLERANCE = 1e-8  # metres


def read_vertices(data):
    """Read geometry positions; OBJ materials, normals and UVs are irrelevant."""
    vertices = []
    for line in data.decode("utf-8").splitlines():
        fields = line.split()
        if fields and fields[0] == "v":
            if len(fields) < 4:
                raise ValueError("OBJ vertex needs three coordinates")
            vertices.append([float(value) for value in fields[1:4]])
    points = np.asarray(vertices, dtype=np.float64)
    if len(points) < 4 or not np.isfinite(points).all():
        raise ValueError("Mesh needs at least four finite vertices")
    return points


def convex_mesh(points):
    """Return lexicographically ordered vertices and outward-facing triangles."""
    points = np.unique(points, axis=0)
    hull = ConvexHull(points)
    used = sorted(hull.vertices)
    indices = {old: new for new, old in enumerate(used)}
    vertices = points[used]
    faces = []
    for triangle, plane in zip(hull.simplices, hull.equations):
        a, b, c = points[triangle]
        normal = np.cross(b - a, c - a)
        if np.dot(normal, plane[:3]) < 0:
            triangle = triangle[[0, 2, 1]]
        face = [indices[index] for index in triangle]
        first = face.index(min(face))
        faces.append(tuple(face[first:] + face[:first]))
    faces = np.asarray(sorted(faces), dtype=np.int64)
    validate_mesh(vertices, faces, points)
    return vertices, faces


def validate_mesh(vertices, faces, source_points):
    """Check closure, outward normals and conservative source coverage."""
    triangles = vertices[faces]
    normals = np.cross(triangles[:, 1] - triangles[:, 0],
                       triangles[:, 2] - triangles[:, 0])
    lengths = np.linalg.norm(normals, axis=1)
    if not np.isfinite(normals).all() or np.any(lengths == 0):
        raise ValueError("Hull contains an invalid triangle")
    normals /= lengths[:, None]
    centre = vertices.mean(axis=0)
    if np.any(np.einsum("ij,ij->i", normals, triangles[:, 0] - centre) <= 0):
        raise ValueError("Hull triangle winding is not outward")
    edges = Counter((int(a), int(b)) for face in faces
                    for a, b in zip(face, np.roll(face, -1)))
    if any(count != 1 or edges[(b, a)] != 1
           for (a, b), count in edges.items()):
        raise ValueError("Hull is not a closed, consistently wound surface")
    offsets = np.einsum("ij,ij->i", normals, triangles[:, 0])
    for start in range(0, len(source_points), 1024):
        distances = source_points[start:start + 1024] @ normals.T - offsets
        if np.max(distances) > TOLERANCE:
            raise ValueError("Hull does not enclose all source vertices")


def generate(source, paths):
    headers = ["# Conservative convex hull; coordinates in metres, source link frame.",
               "# Generated by tools/generate_collision_meshes.py; see LICENSE."]
    inputs = []
    for relative in paths:
        data = (source / relative).read_bytes()
        headers.append(f"# Source: spot_description/{relative}")
        headers.append(f"# SHA256: {hashlib.sha256(data).hexdigest()}")
        inputs.append(read_vertices(data))
    points = np.concatenate(inputs)
    vertices, faces = convex_mesh(points)
    # Validate the serialized precision too, not only the in-memory hull.
    vertex_lines = ["v " + " ".join(f"{value:.12g}" for value in vertex)
                    for vertex in vertices]
    serialized_vertices = read_vertices(("\n".join(vertex_lines) + "\n").encode())
    validate_mesh(serialized_vertices, faces, np.unique(points, axis=0))
    face_lines = ["f " + " ".join(str(index + 1) for index in face) for face in faces]
    data = ("\n".join(headers + vertex_lines + face_lines) + "\n").encode("utf-8")
    return data, len(vertices), len(faces)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True,
                        help="spot_description package share/source directory containing meshes")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "config" / "collision")
    parser.add_argument("--check", action="store_true",
                        help="compare generated OBJ bytes without writing files")
    args = parser.parse_args()
    generated = {name: generate(args.source, paths) for name, paths in SOURCES.items()}
    mismatches = []
    if not args.check:
        args.output.mkdir(parents=True, exist_ok=True)
    for name, (data, vertices, faces) in generated.items():
        path = args.output / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                mismatches.append(str(path))
        else:
            path.write_bytes(data)
        print(f"{name}: {vertices} vertices, {faces} triangles; closed and source-enclosing")
    if mismatches:
        parser.exit(1, "Generated meshes differ: " + ", ".join(mismatches) + "\n")
    if args.check:
        print("All generated OBJ files match.")


if __name__ == "__main__":
    main()
